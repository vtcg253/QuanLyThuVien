-- tạo bảng

--  the loai
CREATE TABLE THELOAI (
    MATL       VARCHAR2(10) CONSTRAINT PK_THELOAI PRIMARY KEY,
    TENTHELOAI NVARCHAR2(100) NOT NULL
);

-- tac gia
CREATE TABLE TACGIA (
    MATG      VARCHAR2(10) CONSTRAINT PK_TACGIA PRIMARY KEY,
    TENTACGIA NVARCHAR2(100) NOT NULL,
    DIACHI    NVARCHAR2(200)
);

-- nhà xuất bản
CREATE TABLE NHAXUATBAN (
    MANXB  VARCHAR2(10) CONSTRAINT PK_NHAXUATBAN PRIMARY KEY,
    TENNXB NVARCHAR2(100) NOT NULL,
    DIACHI NVARCHAR2(200),
    SDT    VARCHAR2(15)
);

-- độc giả
CREATE TABLE DOCGIA (
    MADG     VARCHAR2(10) CONSTRAINT PK_DOCGIA PRIMARY KEY,
    HOTEN    NVARCHAR2(100) NOT NULL,
    NGAYSINH DATE,
    SDT      VARCHAR2(15),
    DIACHI   NVARCHAR2(200)
);

-- nhân viên (thủ thư)
CREATE TABLE NHANVIEN (
    MANV     VARCHAR2(10) CONSTRAINT PK_NHANVIEN PRIMARY KEY,
    HOTEN    NVARCHAR2(100) NOT NULL,
    NGAYSINH DATE,
    SDT      VARCHAR2(15),
    DIACHI   NVARCHAR2(200)
);

-- Nếu đã tạo các bảng trước đó, chỉ chạy riêng khối CREATE TABLE TAIKHOAN này.
-- Tài khoản đăng nhập liên kết 1-1 với nhân viên/thủ thư.
-- MATKHAU được ứng dụng lưu dưới dạng BCrypt hash, không phải mật khẩu thuần.
CREATE TABLE TAIKHOAN (
    MANV        VARCHAR2(10) CONSTRAINT PK_TAIKHOAN PRIMARY KEY,
    TENDANGNHAP VARCHAR2(50) NOT NULL,
    MATKHAU     VARCHAR2(100) NOT NULL,
    VAITRO      VARCHAR2(20) DEFAULT 'THU_THU' NOT NULL,
    KICHHOAT    CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT UQ_TAIKHOAN_TENDANGNHAP UNIQUE (TENDANGNHAP),
    CONSTRAINT FK_TAIKHOAN_NHANVIEN FOREIGN KEY (MANV)
        REFERENCES NHANVIEN(MANV) ON DELETE CASCADE,
    CONSTRAINT CHK_TAIKHOAN_VAITRO CHECK (VAITRO IN ('ADMIN', 'THU_THU')),
    CONSTRAINT CHK_TAIKHOAN_KICHHOAT CHECK (KICHHOAT IN ('Y', 'N'))
);

-- Bảng sách (Liên kết khóa ngoại tới Thể loại, Tác giả, NXB)
CREATE TABLE SACH (
    MASACH     VARCHAR2(10) CONSTRAINT PK_SACH PRIMARY KEY,
    TENSACH    NVARCHAR2(200) NOT NULL,
    MATL       VARCHAR2(10),
    MATG       VARCHAR2(10),
    MANXB      VARCHAR2(10),
    NAMXUATBAN NUMBER,
    SOLUONG    NUMBER DEFAULT 0 CONSTRAINT CHK_SACH_SOLUONG CHECK (SOLUONG >= 0),
    CONSTRAINT FK_SACH_THELOAI FOREIGN KEY (MATL) REFERENCES THELOAI(MATL),
    CONSTRAINT FK_SACH_TACGIA FOREIGN KEY (MATG) REFERENCES TACGIA(MATG),
    CONSTRAINT FK_SACH_NHAXUATBAN FOREIGN KEY (MANXB) REFERENCES NHAXUATBAN(MANXB)
);

-- Tạo bảng nghiệp vụ mượn - trả sách

-- bảng phiếu mượn
CREATE TABLE PHIEUMUON (
    MAPM        VARCHAR2(10) CONSTRAINT PK_PHIEUMUON PRIMARY KEY,
    MADG        VARCHAR2(10) NOT NULL,
    MANV        VARCHAR2(10) NOT NULL,
    NGAYMUON    DATE DEFAULT SYSDATE NOT NULL,
    NGAYHANTRA  DATE NOT NULL,
    TRANGTHAI   NVARCHAR2(50) DEFAULT N'Đang mượn',
    CONSTRAINT FK_PM_DOCGIA FOREIGN KEY (MADG) REFERENCES DOCGIA(MADG),
    CONSTRAINT FK_PM_NHANVIEN FOREIGN KEY (MANV) REFERENCES NHANVIEN(MANV),
    CONSTRAINT CHK_PM_NGAY CHECK (NGAYHANTRA >= NGAYMUON)
);

-- bảng ctiet phiếu mượn (Khóa chính phức hợp MAPM + MASACH)
CREATE TABLE CT_PHIEUMUON (
    MAPM      VARCHAR2(10) NOT NULL,
    MASACH    VARCHAR2(10) NOT NULL,
    SOLUONG   NUMBER DEFAULT 1 CONSTRAINT CHK_CTPM_SOLUONG CHECK (SOLUONG > 0),
    NGAYTRA   DATE,
    TINHTRANG NVARCHAR2(100),
    CONSTRAINT PK_CT_PHIEUMUON PRIMARY KEY (MAPM, MASACH),
    CONSTRAINT FK_CTPM_PHIEUMUON FOREIGN KEY (MAPM) REFERENCES PHIEUMUON(MAPM),
    CONSTRAINT FK_CTPM_SACH FOREIGN KEY (MASACH) REFERENCES SACH(MASACH)
);

-- thống kê số lượng sách
SELECT
    S.MASACH,
    S.TENSACH,
    S.SOLUONG AS SL_TREN_KE,
    NVL(SUM(CASE WHEN CT.NGAYTRA IS NULL THEN CT.SOLUONG ELSE 0 END), 0) AS SL_DANG_MUON,
    (S.SOLUONG + NVL(SUM(CASE WHEN CT.NGAYTRA IS NULL THEN CT.SOLUONG ELSE 0 END), 0)) AS TONG_SL_THUC_TE
FROM SACH S
LEFT JOIN CT_PHIEUMUON CT ON S.MASACH = CT.MASACH
GROUP BY S.MASACH, S.TENSACH, S.SOLUONG
ORDER BY S.MASACH;



-- TRIGGER
-- TỰ ĐỘNG TRỪ KHO KHI MƯỢN SÁCH
CREATE OR REPLACE TRIGGER TRG_CTPM_MUON_SACH
AFTER INSERT ON CT_PHIEUMUON
FOR EACH ROW
DECLARE
    v_ton_kho NUMBER;
BEGIN
    -- Lấy số lượng tồn kho hiện tại
    SELECT SOLUONG INTO v_ton_kho
    FROM SACH
    WHERE MASACH = :NEW.MASACH;

    -- Cảnh báo nếu số lượng trong kho không đủ
    IF v_ton_kho < :NEW.SOLUONG THEN
        RAISE_APPLICATION_ERROR(-20001, 'Lỗi: Số lượng sách trong kho không đủ để cho mượn!');
    END IF;

    -- Tự động trừ kho
    UPDATE SACH
    SET SOLUONG = SOLUONG - :NEW.SOLUONG
    WHERE MASACH = :NEW.MASACH;
END;
/
-- TỰ ĐỘNG CỘNG HOÀN KHO KHI TRẢ SÁCH
CREATE OR REPLACE TRIGGER TRG_CTPM_TRA_SACH
AFTER UPDATE OF NGAYTRA ON CT_PHIEUMUON
FOR EACH ROW
WHEN (OLD.NGAYTRA IS NULL AND NEW.NGAYTRA IS NOT NULL)
BEGIN
    -- Tự động cộng trả lại sách vào kho
    UPDATE SACH
    SET SOLUONG = SOLUONG + :NEW.SOLUONG
    WHERE MASACH = :NEW.MASACH;
END;
/


-- DẠNG XEM THÔNG TIN SÁCH ĐẦY ĐỦ (KÈM TÊN TL, TG, NXB)
CREATE OR REPLACE VIEW V_DANH_SACH_SACH AS
SELECT
    s.MASACH,
    s.TENSACH,
    tl.TENTHELOAI,
    tg.TENTACGIA,
    nxb.TENNXB,
    s.NAMXUATBAN,
    s.SOLUONG AS TON_KHO
FROM SACH s
LEFT JOIN THELOAI tl ON s.MATL = tl.MATL
LEFT JOIN TACGIA tg ON s.MATG = tg.MATG
LEFT JOIN NHAXUATBAN nxb ON s.MANXB = nxb.MANXB;

-- DẠNG XEM DANH SÁCH SÁCH MƯỢN QUÁ HẠN (CẢNH BÁO)
CREATE OR REPLACE VIEW V_SACH_QUA_HAN AS
SELECT
    pm.MAPM,
    dg.HOTEN AS TEN_DOCGIA,
    dg.SDT,
    s.TENSACH,
    pm.NGAYMUON,
    pm.NGAYHANTRA,
    TRUNC(SYSDATE - pm.NGAYHANTRA) AS SO_NGAY_QUA_HAN
FROM PHIEUMUON pm
JOIN CT_PHIEUMUON ct ON pm.MAPM = ct.MAPM
JOIN DOCGIA dg ON pm.MADG = dg.MADG
JOIN SACH s ON ct.MASACH = s.MASACH
WHERE ct.NGAYTRA IS NULL
  AND SYSDATE > pm.NGAYHANTRA;






